/** Fuzzy-match catalog + custom macros by both LaTeX command and English keywords. */
export function searchCatalog(
  rawQuery: string,
  extraItems: LatexCatalogItem[] = [],
  recent: string[] = [],
  limit = 40,
): LatexCatalogItem[] {
  const q = rawQuery.trim().toLowerCase();
  const qNoSlash = q.replace(/^\\+/, '');
  const recentRank = new Map(recent.map((cmd, i) => [cmd, i]));
  const all = [...extraItems, ...LATEX_CATALOG];

  if (!qNoSlash) {
    return all.slice(0, limit);
  }

  const scored: Array<{ item: LatexCatalogItem; score: number }> = [];
  const seen = new Set<string>();

  for (const item of all) {
    if (seen.has(item.cmd)) continue;
    const cmdLower = item.cmd.toLowerCase();
    const cmdBare = cmdLower.replace(/^\\+/, '');
    const labelLower = item.label.toLowerCase();

    let score = 999;
    if (cmdBare === qNoSlash || cmdLower === q) score = 0;
    else if (cmdBare.startsWith(qNoSlash)) score = 10 + (cmdBare.length - qNoSlash.length) * 0.1;
    else if (item.keywords.some((k) => k.toLowerCase() === qNoSlash)) score = 15;
    else if (labelLower.startsWith(qNoSlash)) score = 20;
    else if (item.keywords.some((k) => k.toLowerCase().startsWith(qNoSlash))) score = 25;
    else if (cmdBare.includes(qNoSlash)) score = 35;
    else if (labelLower.includes(qNoSlash) || item.keywords.some((k) => k.toLowerCase().includes(qNoSlash))) score = 45;
    else if (isSubsequence(qNoSlash, cmdBare)) score = 60 + (cmdBare.length - qNoSlash.length) * 0.2;

    if (score < 999) {
      seen.add(item.cmd);
      const r = recentRank.get(item.cmd);
      if (r !== undefined) score -= Math.max(1, 6 - r * 0.4);
      scored.push({ item, score });
    }
  }

  scored.sort((a, b) => a.score - b.score || a.item.cmd.length - b.item.cmd.length);
  return scored.slice(0, limit).map((s) => s.item);
}

function isSubsequence(needle: string, haystack: string): boolean {
  if (needle.length < 2 || needle.length > haystack.length) return false;
  let j = 0;
  for (let i = 0; i < haystack.length && j < needle.length; i++) {
    if (haystack[i] === needle[j]) j++;
  }
  return j === needle.length;
}
